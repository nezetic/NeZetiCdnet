-- | A language the site is available in.
--
-- The default language (French) lives at the root of the site, every other
-- language is served below a prefix (English below @\/en\/@).  Because a
-- language's source files are stored under the very same prefix, the routing
-- of both languages is identical.
data Language = Language
    { langCode          :: String -- ^ ISO 639-1 code, also used as @<html lang>@.
    , langPrefix        :: String -- ^ Source/route prefix, @""@ or @"en\/"@.
    , langLabel         :: String -- ^ Name shown in the language switcher.
    , langDateFormat    :: String -- ^ @strftime@ format of the @date@ field.
    , trHome            :: String -- ^ Title of the home page.
    , trSiteDescription :: String -- ^ Fallback @description@ for @<meta>@.
    , trAllWritings     :: String -- ^ Title of the all-posts page.
    , trRecentArticles  :: String -- ^ Heading of the recent articles list.
    , trArticlesByCat   :: String -- ^ Heading of the per-category article list.
    , trReadMore        :: String -- ^ "Read more" link of a teaser.
    , trProjects        :: String -- ^ Heading of the sidebar projects list.
    , trRssTitle        :: String -- ^ Title of the sidebar RSS link.
    , trBy              :: String -- ^ Author prefix in a signature.
    , trOn              :: String -- ^ Date prefix in a signature.
    , trGeneratedBy     :: String -- ^ Footer credit.
    , trThemeToggle     :: String -- ^ Label of the dark mode toggle button.
    , trFeedTitle       :: String
    , trFeedDescription :: String
    }


